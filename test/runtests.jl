#test stadium in fundamental domain
@testset "Stadium billiard" begin
    billiard = Stadium(0.5) 
    p = PointParticle(1.0,0.6,-1.0,1.3;subdomain=1)
    T = 5
    pts, vel, ts  = trajectory(p,billiard,T; dt = 0.1, full_domain=false)
    test_pts = SVector{2, Float64}[[1.0, 0.6], [0.7093538925354034, 0.9778399397039756], [0.0, 0.5964920777962801], [1.1095485762910564, 0.0], [1.4799712872329833, 0.19913883649085065], [5.551115123125783e-17, 0.33615065038033126]]
    @test all(isapprox.(pts, test_pts; atol=1e-8))
end

